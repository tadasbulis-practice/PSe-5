-- SimpleStudent – PostgreSQL (the postgres Docker container or Supabase)
--
-- Docker:   runs automatically ONCE, when the postgres container starts with an empty volume
--           (the Dockerfile next to this file copies it to /docker-entrypoint-initdb.d).
--           The database "StudentDb" is created by POSTGRES_DB, this script runs inside it.
-- Supabase: open the project → SQL Editor → paste this file → Run. (The database there is "postgres".)
-- Manually: psql -h localhost -U postgres -d StudentDb -f database/postgres/create.sql
--
-- Safe to run more than once.
--
-- Names in double quotes keep their capital letters ("Students", "FirstName"). These are exactly the names
-- the .NET API (EF Core) uses, so the Node.js API – and later any other API – can share this table.

CREATE TABLE IF NOT EXISTS "Students" (
    "Id"             integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- = IDENTITY(1,1) in SQL Server
    "FirstName"      varchar(100) NOT NULL,                                        -- PostgreSQL text is always Unicode
    "LastName"       varchar(100) NOT NULL,
    "Email"          varchar(200) NOT NULL,
    "StudyProgram"   varchar(100) NOT NULL,
    "EnrollmentYear" integer      NOT NULL
);

-- Demo data (only if the table is empty)
