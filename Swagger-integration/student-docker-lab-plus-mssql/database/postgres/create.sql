WHERE NOT EXISTS (SELECT 1 FROM "Students");

-- Supabase publishes every table of the "public" schema through its own REST API (anon key).
-- Row Level Security without any policy closes that door; our APIs connect as the table owner
-- (user postgres), which RLS does not restrict. In the local container this line changes nothing.
ALTER TABLE "Students" ENABLE ROW LEVEL SECURITY;
