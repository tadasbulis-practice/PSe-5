"""
Pydantic models = the API contract.

FastAPI turns these classes into the schemas of swagger.json (code-first, like Swashbuckle in .NET):
  Field(max_length=100)          → "maxLength": 100
  Field(ge=2000, le=2100)        → "minimum": 2000, "maximum": 2100
  a field without a default      → listed in "required"
  json_schema_extra              → anything else (readOnly, format: email, examples)

JSON uses camelCase (firstName) while Python uses snake_case (first_name):
the alias generator translates between the two, so the JSON is identical to the .NET and PHP APIs.
"""

from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, field_validator
from pydantic.alias_generators import to_camel


class ApiModel(BaseModel):
    """Base class: camelCase in JSON, snake_case in Python."""
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)


class Student(ApiModel):
    """A student stored in the database table `Students`."""

    id: int = Field(0, description="Database ID (generated by the database; ignored when creating).",
                    json_schema_extra={"readOnly": True, "format": "int32", "example": 1})
    first_name: str = Field(..., max_length=100, description="First name.",
                            json_schema_extra={"example": "Jonas"})
    last_name: str = Field(..., max_length=100, description="Last name.",
                           json_schema_extra={"example": "Jonaitis"})
    email: str = Field(..., max_length=200, description="University email address.",
                       json_schema_extra={"format": "email", "example": "jonas@university.lt"})
    study_program: str = Field(..., max_length=100, description="Study program, e.g. Computer Science.",
                               json_schema_extra={"example": "Computer Science"})
    enrollment_year: int = Field(0, ge=2000, le=2100, validate_default=True,
                                 description="Year the student started studying (2000–2100).",
                                 json_schema_extra={"format": "int32", "example": 2024})

    # The same checks as StudentValidator in the .NET API
    @field_validator("first_name", "last_name", "study_program")
    @classmethod
    def not_blank(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("must not be blank")
        return value

    @field_validator("email")
    @classmethod
    def looks_like_email(cls, value: str) -> str:
        if "@" not in value:
            raise ValueError("must contain @")
        return value


class InfoResponse(ApiModel):
    """Basic information about the running API."""
    service: str = Field(json_schema_extra={"example": "SimpleStudentPythonApi"})
    version: str = Field(json_schema_extra={"example": "1.2"})
    status: str = Field(description='"ok" when the service is healthy.', json_schema_extra={"example": "ok"})
    message: str = Field(json_schema_extra={"example": "Student CRUD API in Python + FastAPI"})
    environment: str = Field(description="Environment (Development / Docker / Production).",
                             json_schema_extra={"example": "Docker"})
    endpoints: list[str] = Field(description="Main endpoints of this API.")
    timestamp_utc: datetime = Field(description="Server time in UTC.")


class GroupResponse(ApiModel):
    code: str
    study_program: str
    enrollment_year: int
    students: list[Student]


class FacultyResponse(ApiModel):
    """Response for GET /api/faculty: faculty → groups → students."""
    name: str = "Faculty of Technology"
    groups: list[GroupResponse] = []


class HttpValidationProblemDetails(BaseModel):
    """RFC 9457 problem details with field errors – the same shape as ValidationProblem in ASP.NET Core."""
    type: str | None = None
    title: str | None = None
    status: int | None = None
    detail: str | None = None
    instance: str | None = None
    errors: dict[str, list[str]] = {}
